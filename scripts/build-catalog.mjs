#!/usr/bin/env node
// Writes public/js/content/catalog.js: the titles and summaries of every topic, so the app can draw
// its menus without downloading lesson content. Run `npm run catalog` after adding or renaming a topic.
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { LEVELS } from '../public/js/content/index.js';

export async function buildCatalog() {
  const catalog = {};
  for (const level of LEVELS) {
    const topics = (await level.load()).default;
    catalog[level.id] = topics.map((t) => ({ id: t.id, title: t.title, summary: t.summary, grade: t.grade ?? null, standards: t.standards }));
  }
  return catalog;
}

export function catalogSource(catalog) {
  return `// Generated by \`npm run catalog\`. Do not edit by hand.\nexport const CATALOG = ${JSON.stringify(catalog, null, 2)};\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const catalog = await buildCatalog();
  const file = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../public/js/content/catalog.js');
  await writeFile(file, catalogSource(catalog));
  const total = Object.values(catalog).reduce((a, list) => a + list.length, 0);
  console.log(`catalog.js written: ${total} topics in ${Object.keys(catalog).length} levels.`);
}
